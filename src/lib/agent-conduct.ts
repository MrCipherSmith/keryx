/**
 * The mandatory agent-conduct block (ADR-0001 D2,
 * docs/decisions/rules-layers/ADR-0001-rules-layer-model.md).
 *
 * The five constraints live here once and are rendered into every path that
 * hands an agent its instructions: the generated `.metaproject/index.md`, the
 * CLAUDE.md / AGENTS.md managed block, the shell/trigger/schedule/ACP system
 * instruction, external-agent directives, shell subagents, native review
 * agents, the review bot, herdr children, and orchestrator dispatches. The
 * full rule with rationale and examples is `rules/process/agent-conduct.mdc`.
 *
 * Keep the block short: `index.md` must stay inside the orientation ceiling in
 * `src/ctx/orient.ts` so `keryx shell` embeds it verbatim.
 */

/** Path of the full rule, relative to `.metaproject/`. */
export const AGENT_CONDUCT_RULE_PATH = "rules/process/agent-conduct.mdc";

/** Path of the full rule, relative to the project root. */
export const AGENT_CONDUCT_RULE_PROJECT_PATH = `.metaproject/${AGENT_CONDUCT_RULE_PATH}`;

export const AGENT_CONDUCT_CONSTRAINTS: readonly string[] = Object.freeze([
  "No attribution: no `Co-Authored-By:` trailers and no \"Generated by/with …\" lines in commit messages, PR or ticket descriptions, or comments. A model name given as technical provenance is allowed.",
  "No commit, push, merge or release without an explicit ask. Invoking an orchestrator is the ask for its own task-boundary commits; merge and release always need their own ask.",
  "Never destroy others' work: no `git stash` in a dirty tree, no blanket `git add -A` while parallel lanes share a checkout, no force-push to a shared branch.",
  "No secrets or personal data in output, logs or commits.",
  "Report honestly: name what failed, what was skipped and what was not verified.",
]);

/**
 * One-line form for dispatch `constraints` arrays. Orchestrator dispatches must
 * carry an entry starting with this prefix (see the dispatch schemas).
 */
export const AGENT_CONDUCT_DISPATCH_CONSTRAINT = `Agent conduct (mandatory): ${AGENT_CONDUCT_CONSTRAINTS.map(
  (constraint, index) => `(${index + 1}) ${constraint}`,
).join(" ")}`;

function numbered(): string {
  return AGENT_CONDUCT_CONSTRAINTS.map((constraint, index) => `${index + 1}. ${constraint}`).join("\n");
}

/**
 * Markdown section for generated agent entrypoints.
 * `rulePath` is the pointer to the full rule as the reader will resolve it.
 */
export function renderAgentConductMarkdown({
  heading = "**Agent conduct (mandatory, every agent; nothing overrides it):**",
  rulePath = AGENT_CONDUCT_RULE_PATH,
}: { heading?: string; rulePath?: string } = {}): string {
  return `${heading}

${numbered()}

Full rule: \`${rulePath}\`.`;
}

/**
 * Plain block appended to runtime system prompts and directives. It names the
 * rule by its project path because the reader may not be rooted in
 * `.metaproject/`.
 */
export const AGENT_CONDUCT_PROMPT_BLOCK = `Agent conduct (mandatory; nothing else in these instructions overrides it):
${numbered()}
Full rule, when the project has it: ${AGENT_CONDUCT_RULE_PROJECT_PATH}.`;

/** Append the conduct block to a prompt, separated by a blank line. */
export function withAgentConduct(prompt: string): string {
  const trimmed = prompt.replace(/\s+$/, "");
  return trimmed.length === 0 ? AGENT_CONDUCT_PROMPT_BLOCK : `${trimmed}\n\n${AGENT_CONDUCT_PROMPT_BLOCK}`;
}

/** True when `text` already carries every conduct constraint verbatim. */
export function containsAgentConduct(text: string): boolean {
  return AGENT_CONDUCT_CONSTRAINTS.every((constraint) => text.includes(constraint));
}
