import { constants } from "node:fs";
import { lstat, open, realpath } from "node:fs/promises";
import path from "node:path";
import type { ProtocolResult } from "../../remote-control/protocol";
import type { CiSourceSpawn, CiSpawnResult } from "../../tui/ci-triage-source";

export class AnalysisReadError extends Error {
  constructor(readonly code: "invalid-argv" | "invalid-cwd" | "read-denied" | "read-failed" | "quota-exceeded" | "cancelled") {
    super(code); this.name = "AnalysisReadError";
  }
}
type Predicate = (value: string) => boolean;
type Pattern = readonly (string | Predicate)[];
const identifier: Predicate = (value) => /^[1-9]\d{0,19}$/.test(value);
const hash: Predicate = (value) => /^[a-f0-9]{7,64}$/i.test(value);
const label: Predicate = (value) => value.length > 0 && value.length <= 200 && !value.startsWith("-") && [...value].every((char) => char.charCodeAt(0) >= 32 && char.charCodeAt(0) !== 127);
const limit: Predicate = (value) => /^(?:[1-9]|1\d|20)$/.test(value);
const repo: Predicate = (value) => /^[A-Za-z0-9_][A-Za-z0-9_.-]{0,99}\/[A-Za-z0-9_][A-Za-z0-9_.-]{0,99}$/.test(value);
const commitRoute: Predicate = (value) => /^repos\/(?:\{owner\}\/\{repo\}|[A-Za-z0-9_][A-Za-z0-9_.-]{0,99}\/[A-Za-z0-9_][A-Za-z0-9_.-]{0,99})\/commits\/[a-f0-9]{7,64}$/i.test(value);
const patterns: readonly Pattern[] = [
  ["gh", "pr", "view", "--json", "number,headRefName"], ["gh", "pr", "view", "--json", "number,title"],
  ["gh", "pr", "view", identifier, "--json", "title,body"], ["gh", "pr", "diff", identifier],
  ["gh", "run", "view", identifier, "--json", "jobs,workflowName,headBranch,headSha,conclusion"],
  ["gh", "run", "view", identifier, "--json", "attempt"], ["gh", "run", "view", identifier, "--json", "jobs"],
  ["gh", "run", "view", identifier, "--attempt", identifier, "--json", "jobs"], ["gh", "run", "view", identifier, "--log-failed"],
  ["gh", "run", "list", "--branch", label, "--json", "databaseId,conclusion,workflowName,headBranch,createdAt", "-L", limit],
  ["gh", "run", "list", "--workflow", label, "--json", "databaseId,conclusion,createdAt,headBranch", "-L", limit],
  ["gh", "run", "list", "--workflow", label, "--commit", hash, "--json", "databaseId,conclusion,createdAt,headBranch", "-L", limit],
  ["gh", "api", commitRoute, "--jq", ".files[].filename"],
];

/** Only argv generated by ci-triage-source, ci-port and conform-pr-port. No remote executable or option passthrough. */
export function validateAnalysisReadArgv(input: readonly string[]): ProtocolResult<readonly string[]> {
  const original = [...input]; const argv = [...input];
  const repoIndex = argv.indexOf("--repo");
  if (repoIndex >= 0) {
    const permittedIndex = argv[1] === "run" && argv[2] === "list" ? repoIndex === 3
      : argv[1] === "run" && argv[2] === "view" ? repoIndex === 4 || repoIndex === 6
      : argv[1] === "pr" && ["view", "diff"].includes(argv[2] ?? "") && identifier(argv[3] ?? "") && repoIndex === 4;
    if (!permittedIndex || !repo(argv[repoIndex + 1] ?? "")) return invalidArgv();
    argv.splice(repoIndex, 2); if (argv.includes("--repo")) return invalidArgv();
  }
  const match = patterns.some((pattern) => argv.length === pattern.length && pattern.every((part, index) => typeof part === "string" ? argv[index] === part : part(argv[index] ?? "")));
  return match ? { ok: true, value: Object.freeze(original) } : invalidArgv();
}
function invalidArgv(): ProtocolResult<never> { return { ok: false, error: { code: "invalid-argv", message: "The local analysis read is not permitted." } }; }

export interface AnalysisReadPortOptions {
  cwd: string;
  /** Must supervise its own process, stop on signal/timeout and cap each stream BEFORE buffering. */
  runOwned(argv: readonly string[], signal?: AbortSignal): Promise<CiSpawnResult>;
}
export function createAnalysisReadPorts(options: AnalysisReadPortOptions): {
  ciSpawn: CiSourceSpawn;
  readReference(relativePath: string, signal: AbortSignal): Promise<string>;
} {
  return {
    ciSpawn: async (argv, requestedCwd, signal) => {
      if (signal?.aborted) throw new AnalysisReadError("cancelled");
      const validated = validateAnalysisReadArgv(argv); if (!validated.ok) throw new AnalysisReadError("invalid-argv");
      const [expected, requested] = await Promise.all([realpath(options.cwd), realpath(requestedCwd)]).catch(() => { throw new AnalysisReadError("invalid-cwd"); });
      if (expected !== requested) throw new AnalysisReadError("invalid-cwd");
      const result = await options.runOwned(validated.value, signal);
      if (signal?.aborted) throw new AnalysisReadError("cancelled");
      if (Buffer.byteLength(result.stdout, "utf8") > 512 * 1024 || Buffer.byteLength(result.stderr, "utf8") > 512 * 1024) throw new AnalysisReadError("quota-exceeded");
      return result;
    },
    readReference: async (relativePath, signal) => {
      const result = await readProjectReference(options.cwd, relativePath, signal);
      if (!result.ok) throw new AnalysisReadError(result.error.code as AnalysisReadError["code"]);
      return result.value;
    },
  };
}

/** Contained bounded descriptor read: symlinks are rejected before opening and the descriptor identity is checked before reading. */
export async function readProjectReference(cwd: string, relativePath: string, signal: AbortSignal): Promise<ProtocolResult<string>> {
  if (signal.aborted) return readFailure("cancelled");
  const parts = relativePath.split("/");
  if (relativePath !== "project.md" || path.isAbsolute(relativePath) || relativePath.includes("\\") || parts.some((part) => !part || part === "." || part === "..")) return readFailure("read-denied");
  try {
    const root = await realpath(cwd); let candidate = root;
    for (let index = 0; index < parts.length; index++) {
      candidate = path.join(candidate, parts[index]!); const info = await lstat(candidate);
      if (info.isSymbolicLink() || (index < parts.length - 1 && !info.isDirectory())) return readFailure("read-denied");
    }
    const before = await lstat(candidate);
    if (!before.isFile()) return readFailure("read-denied");
    if (before.size > 128 * 1024) return readFailure("quota-exceeded");
    const handle = await open(candidate, constants.O_RDONLY | constants.O_NOFOLLOW);
    try {
      const actual = await handle.stat();
      if (!actual.isFile() || actual.dev !== before.dev || actual.ino !== before.ino) return readFailure("read-denied");
      const bytes = Buffer.alloc(128 * 1024 + 1); let offset = 0;
      while (offset < bytes.length) {
        if (signal.aborted) return readFailure("cancelled");
        const read = await handle.read(bytes, offset, bytes.length - offset, offset);
        if (read.bytesRead === 0) break; offset += read.bytesRead;
      }
      if (offset > 128 * 1024) return readFailure("quota-exceeded");
      return { ok: true, value: new TextDecoder("utf-8", { fatal: true }).decode(bytes.subarray(0, offset)) };
    } finally { await handle.close(); }
  } catch { return readFailure(signal.aborted ? "cancelled" : "read-failed"); }
}
function readFailure(code: AnalysisReadError["code"]): ProtocolResult<never> { return { ok: false, error: { code, message: "The local analysis read could not be completed." } }; }
