/** Build-time only: explicit isolated AJV 8.20 runtime; generated artifacts have no runtime dependency. */
import { createRequire } from "node:module";
import { createHash } from "node:crypto";
import { readFileSync, mkdirSync, writeFileSync, unlinkSync } from "node:fs";
import { resolve, join } from "node:path";
const runtime = process.argv[2];
if (!runtime) throw new Error("Pass isolated runtime node_modules path (never install into project node_modules)");
const requireTool = createRequire(join(resolve(runtime), "remote-control-tool.cjs"));
const ajvPackage = requireTool("ajv/package.json") as { version: string };
if (ajvPackage.version !== "8.20.0") throw new Error("Remote protocol generator requires AJV 8.20.0");
const Ajv = requireTool("ajv/dist/2020").default;
const formats = requireTool("ajv-formats").default;
const standalone = requireTool("ajv/dist/standalone").default;
type Schema = { $ref?: string; const?: unknown; enum?: unknown[]; oneOf?: Schema[]; anyOf?: Schema[]; type?: string | string[]; properties?: Record<string, Schema>; required?: string[]; items?: Schema; additionalProperties?: boolean | Schema; $defs?: Record<string, Schema>; $id?: string };
const source = "docs/requirements/hub-remote-sessions/schemas";
const machineBytes = readFileSync(join(source, "machine-protocol.schema.json"), "utf8");
const controlBytes = readFileSync(join(source, "control-api.schema.json"), "utf8");
const digest = (text: string) => createHash("sha256").update(text).digest("hex");
if (digest(machineBytes) !== "1e1c2cbd33110b25229b012296e5688637e879f7c8c69bcaa7d56ee76e2bdfca" || digest(controlBytes) !== "b235475c3071e925d8fe71f918f4c176cc1ad687606e6df1b68765e9ecc23f2b") throw new Error("Frozen protocol schema drift requires explicit contract decision");
const machine = JSON.parse(machineBytes) as Schema; const control = JSON.parse(controlBytes) as Schema;
if (JSON.stringify(machine.$defs) !== JSON.stringify(control.$defs)) throw new Error("Duplicated protocol definitions differ");
function ts(s: Schema): string {
  if (s.$ref) return s.$ref.split("/").at(-1)!;
  if (Object.hasOwn(s, "const")) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (s.oneOf ?? s.anyOf) return (s.oneOf ?? s.anyOf)!.map((v) => `(${ts(v)})`).join(" | ");
  if (Array.isArray(s.type)) return s.type.map((type) => ts({ ...s, type })).join(" | ");
  if (s.type === "object" && typeof s.additionalProperties === "object") return `{ [key: string]: ${ts(s.additionalProperties)} }`;
  if (s.type === "object") return `{ ${Object.entries(s.properties ?? {}).map(([key, value]) => `${JSON.stringify(key)}${s.required?.includes(key) ? "" : "?"}: ${ts(value)};`).join(" ")} }`;
  if (s.type === "array") return `Array<${ts(s.items ?? {})}>`;
  if (s.type === "integer" || s.type === "number") return "number";
  if (s.type === "null") return "null";
  if (s.type === "string" || s.type === "boolean") return s.type;
  return "unknown";
}
const out = "src/remote-control/generated"; mkdirSync(out, { recursive: true });
writeFileSync(join(out, "types.ts"), `// Generated from frozen v2 JSON schemas. Do not edit.\n${Object.entries(control.$defs!).map(([name, schema]) => `export type ${name} = ${ts(schema)};`).join("\n")}\nexport type Control = { ${Object.keys(control.$defs!).map((name) => `${name}: ${name};`).join(" ")} };\nexport type MachineFrame = ${ts(machine)};\n`);
const ajv = new Ajv({ strict: false, allErrors: false, code: { source: true, esm: true }, coerceTypes: false, useDefaults: false, removeAdditional: false });
formats(ajv); ajv.addSchema(control); ajv.addSchema(machine);
const refs: Record<string, string> = { machineFrame: machine.$id! };
for (const name of Object.keys(control.$defs!)) refs[`control_${name}`] = `${control.$id}#/$defs/${name}`;
writeFileSync(join(out, "validators.source.js"), standalone(ajv, refs));
const built = await Bun.build({ entrypoints: [join(out, "validators.source.js")], target: "bun", format: "esm", minify: false, external: [], root: out, naming: "validators.js", plugins: [{ name: "isolated-ajv", setup(build) { build.onResolve({ filter: /^ajv\// }, (args) => ({ path: requireTool.resolve(args.path) })); } }] });
if (!built.success) throw new AggregateError(built.logs, "Failed standalone validator bundling");
unlinkSync(join(out, "validators.source.js"));
writeFileSync(join(out, "validators.js"), await built.outputs[0]!.text());
writeFileSync(join(out, "validators.d.ts"), `type Validator = (value: unknown) => boolean;\n${Object.keys(refs).map((name) => `export const ${name}: Validator;`).join("\n")}\n`);
writeFileSync(join(out, "manifest.json"), JSON.stringify({ protocolVersion: 2, ajv: ajvPackage.version, machineSchemaSha256: digest(machineBytes), controlSchemaSha256: digest(controlBytes), validatorsSha256: digest(await built.outputs[0]!.text()) }, null, 2) + "\n");
console.log(`Generated ${Object.keys(refs).length} pinned v2 validators and wire types`);
